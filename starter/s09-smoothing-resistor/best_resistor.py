# วงจรเหมือนคาบ 8: 3V3 → ตัวต้านทานคงที่ → D0 → flex → GND (งอ = ตัวเลขขึ้น)
# วิธีนับส่วน (คาบ 8): ตัวเลข = 4095 × flex ÷ (ตัวต้านทาน + flex)
# ตัวต้านทานที่ดีที่สุด = ตัวที่ทำให้ "ช่วงห่าง" (งอสุด − เหยียด) กว้างที่สุด
# ช่วงยิ่งกว้าง บอร์ดยิ่งแยกท่าเหยียด / งอครึ่ง / งอสุด ออกจากกันได้ชัด

STRAIGHT_K = 25   # kΩ flex ตอนเหยียด (ค่าใน sim)
BENT_K = 100      # kΩ flex ตอนงอสุด (ค่าใน sim)
CHOICES = [10, 22, 47, 100, 220]   # kΩ ตัวต้านทานที่ลองใน sim


def adc_value(fixed_k, flex_k):
    """ตัวเลขที่บอร์ดอ่านได้ (0–4095) ใช้วิธีนับส่วนของคาบ 8"""
    return round(4095 * flex_k / (fixed_k + flex_k))


