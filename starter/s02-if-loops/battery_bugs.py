# ครั้งที่ 2 — เกมหาบั๊ก: ไฟบอกแบตของถุงมือ
#
# ถุงมือจริงใช้แบตเตอรี่ อยากให้บอกผู้ใช้ว่าแบตเหลือแค่ไหน ตามกฎนี้:
#   50 ขึ้นไป            → แบตพอใช้
#   20 ถึง 49            → แบตใกล้หมด
#   ต่ำกว่า 20            → ชาร์จด่วน
#   ต่ำกว่า 0 หรือเกิน 100 → ค่าแบตต้องอยู่ระหว่าง 0 ถึง 100
#
# โปรแกรมข้างล่างมีบั๊ก 3 จุด กด Run แล้วจะไม่มีตัวแดงขึ้นเลย แต่บางค่าตอบผิด
# 1. ทายก่อนว่าแต่ละค่าในตารางควรได้คำตอบอะไร แล้วรันทีละค่า จดว่าค่าไหนตอบผิด
#      80   50   49   20   19   0   150   -5
# 2. หาว่าผิดเพราะบรรทัดไหน แก้ทีละจุด แล้วรันค่าเดิมซ้ำทุกค่า

percent = int(input("แบตเหลือกี่ %: "))

if percent < 0 and percent > 100:
    print("ค่าแบตต้องอยู่ระหว่าง 0 ถึง 100")
elif percent >= 20:
    print("แบตใกล้หมด")
elif percent > 50:
    print("แบตพอใช้")
else:
    print("ชาร์จด่วน")
