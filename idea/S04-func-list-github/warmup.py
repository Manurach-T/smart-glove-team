# ครั้งที่ 4 · อุ่นเครื่อง def — ร้านชานมของเรา
#
# def = สร้าง "เครื่อง" ไว้ก่อน ยังไม่ทำงานจนกว่าจะเรียกชื่อมันพร้อมวงเล็บ
# ไฟล์นี้ให้ทั้งไฟล์ ไม่มี TODO: รันดู แล้วลองแก้ตามคำถามท้ายไฟล์


# เครื่องแบบที่ 1: ไม่ต้องใส่อะไร ทำงานแล้วพิมพ์ออกจอเลย
def greet():
    print("สวัสดีค่ะ รับอะไรดีคะ")


# เครื่องแบบที่ 2: ใส่ของเข้าไป (พารามิเตอร์) แล้วได้ของกลับออกมา (return)
def make_tea(sweet):
    return "ชานมไข่มุก หวาน " + str(sweet) + "%"


# ใส่ของได้หลายอย่าง คั่นด้วยจุลภาค ลำดับสำคัญ: ตัวแรกคือจำนวนแก้ว ตัวที่สองคือราคา
def total_price(cups, price):
    return cups * price


# ข้างบนแค่ "สร้างเครื่อง" ถ้าลบบรรทัดข้างล่างทั้งหมด กด Run จะไม่มีอะไรขึ้นเลย
greet()
cup = make_tea(50)
print(cup)
print("ต้องจ่าย", total_price(3, 45), "บาท")

# ลองแก้:
# 1. เรียก greet() สองครั้ง จะเห็นอะไร
# 2. make_tea(0) กับ make_tea(100) ได้อะไร
# 3. สลับเป็น total_price(45, 3) ได้เท่าเดิมไหม แล้วถ้าเป็นการหารล่ะ
